#include "parameter_list_base.h"

/** \file argument_list.h
 * This file defines class `argument_list`
 */

// Macro invocation arguments. A null list is distinct from an empty () list.
struct argument_list : innards::parameter_list_base {
	using base = innards::parameter_list_base;
	explicit argument_list(parameter_list_base const & parms) : base(parms) {}
	explicit argument_list(size_t n = 0) : base(n) {}
	template<class CharSeq>
	explicit argument_list(chewer<CharSeq> & chew) { read(chew); }
	template<class CharSeq>
	void read(chewer<CharSeq> & chew);
};
